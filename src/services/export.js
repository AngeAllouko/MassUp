import * as FileSystem from 'expo-file-system/legacy';
import * as Sharing from 'expo-sharing';

export async function exportDailyReport({ profile, targets, day, meals, weightHistory }) {
  const date = new Date().toLocaleDateString('en-US', {
    weekday: 'long', day: 'numeric', month: 'long', year: 'numeric',
  });

  const pct = (v, t) => Math.round((v / (t || 1)) * 100);
  const currentWeight = weightHistory.length > 0
    ? weightHistory[weightHistory.length - 1].value
    : profile.weight;

  const mealLines = meals.length > 0
    ? meals.map((m) => `  - ${m.name} (${m.grams} g): ${m.calories} kcal`).join('\n')
    : '  No meals logged';

  const weightLines = weightHistory.slice(-7).map((p) => `  ${p.date}: ${p.value} kg`).join('\n')
    || '  No weigh-ins recorded';

  const content = `
MASSUP - DAILY REPORT
=====================
${date}

PROFILE
-------
Name           : ${profile.name}
Current weight : ${currentWeight} kg
Level          : ${profile.level}

TODAY'S TARGETS
---------------
Calories       : ${targets.calories} kcal
Protein        : ${targets.protein} g
Carbs          : ${targets.carbs} g
Fat            : ${targets.fat} g
Hydration      : ${targets.water} ml

TODAY'S TOTALS
--------------
Calories       : ${day.calories} kcal (${pct(day.calories, targets.calories)}%)
Protein        : ${day.protein} g (${pct(day.protein, targets.protein)}%)
Carbs          : ${day.carbs} g
Fat            : ${day.fat} g
Water          : ${day.water} ml (${pct(day.water, targets.water)}%)

MEALS LOGGED
------------
${mealLines}

WEIGHT HISTORY (last 7)
-----------------------
${weightLines}

=====================
Generated by MassUp
`.trim();

  const path = `${FileSystem.documentDirectory}MassUp_Report_${new Date().toISOString().split('T')[0]}.txt`;
  await FileSystem.writeAsStringAsync(path, content, { encoding: 'utf8' });

  if (!(await Sharing.isAvailableAsync())) {
    throw new Error('Sharing is not available on this device.');
  }
  await Sharing.shareAsync(path, { mimeType: 'text/plain', dialogTitle: 'Share my MassUp report' });
}
